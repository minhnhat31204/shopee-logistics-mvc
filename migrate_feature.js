const db = require('./config/db');

async function migrate() {
    let conn;
    try {
        conn = await db.getConnection();
        
        // 1. PRODUCT_REVIEWS
        try {
            await conn.execute(`
                CREATE TABLE PRODUCT_REVIEWS (
                    Review_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Order_ID NUMBER NOT NULL,
                    Product_ID NUMBER NOT NULL,
                    SKU VARCHAR2(50) NOT NULL,
                    User_ID NUMBER NOT NULL,
                    Rating NUMBER(2,1) DEFAULT 5,
                    Comment_Text VARCHAR2(2000),
                    Created_At TIMESTAMP DEFAULT SYSTIMESTAMP,
                    CONSTRAINT UQ_REV_ORD_PROD UNIQUE (Order_ID, Product_ID, SKU)
                )
            `);
            console.log('✅ Created PRODUCT_REVIEWS');
        } catch(e) {
            console.log('PRODUCT_REVIEWS info:', e.message);
        }

        // 2. CHAT_MESSAGES
        try {
            await conn.execute(`
                CREATE TABLE CHAT_MESSAGES (
                    Message_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Sender_ID NUMBER,
                    Sender_Name VARCHAR2(100),
                    Sender_Role VARCHAR2(50),
                    Receiver_ID NUMBER,
                    Shop_ID NUMBER,
                    Message_Text VARCHAR2(2000),
                    Is_Auto_Reply NUMBER DEFAULT 0,
                    Created_At TIMESTAMP DEFAULT SYSTIMESTAMP
                )
            `);
            console.log('✅ Created CHAT_MESSAGES');
        } catch(e) {
            console.log('CHAT_MESSAGES info:', e.message);
        }

        // 3. SEARCH_HISTORY
        try {
            await conn.execute(`
                CREATE TABLE SEARCH_HISTORY (
                    Search_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    User_ID NUMBER,
                    Keyword VARCHAR2(255) NOT NULL,
                    Searched_At TIMESTAMP DEFAULT SYSTIMESTAMP
                )
            `);
            console.log('✅ Created SEARCH_HISTORY');
        } catch(e) {
            console.log('SEARCH_HISTORY info:', e.message);
        }

        await conn.commit();
        console.log('✅ Migration done!');
    } catch(err) {
        console.error('Migration error:', err);
    } finally {
        if (conn) await conn.close();
        process.exit(0);
    }
}

migrate();
